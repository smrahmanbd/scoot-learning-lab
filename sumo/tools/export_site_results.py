"""Copy result figures and tables from sumo/results into docs/ (the website).

    python tools/export_site_results.py      (after python run_all.py)
"""
import csv
import json
import os
import shutil

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(HERE, "results")
DOCS = os.path.join(os.path.dirname(HERE), "docs")
ASSETS = os.path.join(DOCS, "assets", "results")

FIGS = {
    "foundation/model_vs_sumo_W_J1.png": "foundation_model_vs_sumo.png",
    "foundation/profile_W_J1.png": "foundation_profile.png",
    "foundation/compare.png": "foundation_compare.png",
    "foundation/node_timeline.png": "foundation_node_timeline.png",
    "advanced/compare.png": "advanced_compare.png",
    "advanced/corridor_timeline.png": "advanced_corridor_timeline.png",
    "advanced/ablation/ablation.png": "advanced_ablation.png",
    "mastery/cv/cv_accuracy.png": "mastery_cv_accuracy.png",
    "mastery/cv/cv_delay.png": "mastery_cv_delay.png",
    "mastery/rl/learning_curve.png": "mastery_rl_curve.png",
    "mastery/maxpressure/maxpressure.png": "mastery_maxpressure.png",
    "mastery/faults/faults.png": "mastery_faults.png",
    "mastery/emissions/stop_weight.png": "mastery_emissions.png",
    "mastery/glosa/glosa_error.png": "mastery_glosa.png",
}
TABLES = {
    "foundation": "foundation/summary.csv",
    "advanced": "advanced/summary.csv",
    "ablation": "advanced/ablation/ablation.csv",
    "cv": "mastery/cv/cv_control.csv",
    "rl": "mastery/rl/rl_vs_scoot.csv",
    "maxpressure": "mastery/maxpressure/maxpressure.csv",
    "faults": "mastery/faults/faults.csv",
    "emissions": "mastery/emissions/stop_weight.csv",
    "glosa": "mastery/glosa/glosa_error.csv",
}

os.makedirs(ASSETS, exist_ok=True)
for src, dst in FIGS.items():
    p = os.path.join(RES, src)
    if os.path.exists(p):
        shutil.copy(p, os.path.join(ASSETS, dst))
out = {}
for key, src in TABLES.items():
    p = os.path.join(RES, src)
    if os.path.exists(p):
        with open(p) as f:
            out[key] = list(csv.DictReader(f))
with open(os.path.join(DOCS, "js", "results.js"), "w") as f:
    f.write("/* generated by sumo/tools/export_site_results.py */\nwindow.RESULTS = " + json.dumps(out, indent=1) + ";\n")
print("exported", len(out), "tables and", len(os.listdir(ASSETS)), "figures")
